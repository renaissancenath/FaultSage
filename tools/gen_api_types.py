"""Generate web/src/api/generated.ts from the Pydantic models (CODE_STYLE.md section 2).

Usage: python tools/gen_api_types.py          (writes the file)
       python tools/gen_api_types.py --check  (exit 1 if the file is out of date; used in CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from faultsage.models import core

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "src" / "api" / "generated.ts"
MODELS = [core.CaseFile, core.IncidentSummary, core.Graph, core.Verification, core.Approval]


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts(s) for s in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    t = schema.get("type")
    if t == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(s) for s in schema["prefixItems"]) + "]"
        return f"Array<{ts(schema.get('items', {}))}>"
    if t == "object":
        add = schema.get("additionalProperties")
        if isinstance(add, dict):
            return f"Record<string, {ts(add)}>"
        return "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(t), "unknown")


def interface(name: str, schema: dict[str, Any]) -> str:
    req = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, s in schema.get("properties", {}).items():
        lines.append(f"  {prop}{'' if prop in req else '?'}: {ts(s)};")
    lines.append("}")
    return "\n".join(lines)


def generate() -> str:
    defs: dict[str, dict[str, Any]] = {}
    for m in MODELS:
        schema = m.model_json_schema(ref_template="#/$defs/{model}", mode="serialization")
        defs.update(schema.pop("$defs", {}))
        defs[m.__name__] = schema
    out = [
        "// Generated by tools/gen_api_types.py from src/faultsage/models. Do not edit by hand.",
        "",
    ]
    for name in sorted(defs):
        s = defs[name]
        if s.get("type") == "object" or "properties" in s:
            out.append(interface(name, s))
        else:
            out.append(f"export type {name} = {ts(s)};")
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date. Run python tools/gen_api_types.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"Written {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
