def test_run_wrapper_records_uncaught_exception(sample_project: Path) -> None:
    (sample_project / "job.py").write_text("import json\njson.loads('{bad')\n")
    r = subprocess.run(
        [sys.executable, "-m", "faultsage.cli.main", "run", "--", sys.executable, "job.py"],
        cwd=sample_project,
        capture_output=True,
        text=True,
    )
    assert r.returncode == 1 and "JSONDecodeError" in r.stderr
    lines = [
        json.loads(line)
        for f in (sample_project / ".faultsage/spool").glob("run_wrapper-*.jsonl")
        for line in f.read_text().splitlines()
    ]
    assert lines and lines[0]["body"]["exception"]["type"] == "JSONDecodeError"


def test_cloud_push_includes_failures_still_in_the_spool(
    sample_project: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Regression: without `faultsage watch` running, push used to find 0 incidents."""
    from typer.testing import CliRunner

    import faultsage.cloud_sync as sync
    from faultsage.cli.main import app

    assert run_pytest(sample_project).returncode == 1  # spooled, not ingested
    sent: list[list[int]] = []
    monkeypatch.setattr(sync, "load_credentials", lambda: {"url": "http://localhost", "key": "k"})
    monkeypatch.setattr(
        sync, "push_incidents", lambda ws, ids, url=None: sent.append(ids) or len(ids)
    )
    monkeypatch.chdir(sample_project)
    r = CliRunner().invoke(app, ["cloud", "push", "all"])
    assert r.exit_code == 0, r.output
    assert sent and len(sent[0]) == 1 and "Sent 1 of 1" in r.output


def test_run_wrapper_does_not_duplicate_pytest_failures(sample_project: Path) -> None:
    r = subprocess.run(
        [sys.executable, "-m", "faultsage", "run", "--", sys.executable, "-m", "pytest", "-q"],
        cwd=sample_project,
        capture_output=True,
        text=True,
    )
    assert r.returncode == 1
    w = Workspace.open(ProjectPaths(sample_project))
    w.ingest()
    titles = [i.title for i in w.list_incidents(None, None, 50, None)[0]]
    assert len(titles) == 1 and "test_fit" in titles[0], titles
