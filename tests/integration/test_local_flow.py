"""End to end on the sample project: plugin -> spool -> incident -> analysis -> gate -> verify."""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

import pytest

from faultsage.config.loader import ProjectPaths
from faultsage.daemon.service import Workspace
from faultsage.errors import GitDirtyError, PatchStaleError
from tests.conftest import git, needs_engine, run_pytest


def project_hashes(root: Path) -> dict[str, str]:
    return {
        str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in root.rglob("*")
        if p.is_file()
        and ".faultsage" not in p.parts
        and ".git" not in p.parts
        and "__pycache__" not in p.parts
        and ".pytest_cache" not in p.parts
    }


@pytest.fixture
def ws(sample_project: Path) -> Workspace:
    r = run_pytest(sample_project)
    assert r.returncode == 1, r.stdout
    w = Workspace.open(ProjectPaths(sample_project))
    w.ingest()
    return w


def test_plugin_never_changes_the_test_outcome(sample_project: Path) -> None:
    with_plugin = run_pytest(sample_project)
    without = subprocess.run(
        ["python", "-m", "pytest", "-q", "-p", "no:faultsage"],
        cwd=sample_project,
        capture_output=True,
        text=True,
    )
    assert with_plugin.returncode == without.returncode == 1


@needs_engine
def test_one_incident_with_ranked_causes(ws: Workspace) -> None:
    items, _ = ws.list_incidents(None, None, 50, None)
    assert len(items) == 1
    cf = ws.case_file(items[0].id)
    assert cf.exception is not None and cf.exception.type == "KeyError"
    assert cf.failing_tests == ["tests/test_train.py::test_fit"]
    top = cf.hypotheses[0]
    assert (
        top.certainty == "possible"  # Strong withheld (D-024)
        and top.location
        and top.location.file_path == "src/churn/clean.py"
    )
    assert cf.suggestions and cf.suggestions[0].patch_diff


def test_ingest_is_idempotent_and_groups_repeats(ws: Workspace, sample_project: Path) -> None:
    run_pytest(sample_project)
    ws.ingest()
    ws.ingest()
    items, _ = ws.list_incidents(None, None, 50, None)
    assert len(items) == 1 and items[0].occurrence_count == 2


def test_invalid_spool_lines_are_rejected_not_fatal(ws: Workspace) -> None:
    (ws.paths.spool / "bad-1-0.jsonl").write_text('{"schema": "nope"}\nnot json\n')
    ws.ingest()
    rejected = list(ws.paths.rejected.glob("*.jsonl"))
    assert rejected and len(rejected[0].read_text().splitlines()) == 2


@needs_engine
def test_nothing_is_written_without_approval(ws: Workspace, sample_project: Path) -> None:
    before = project_hashes(sample_project)
    cf = ws.case_file(1)
    ws.graph("imports", 1)
    ws.scan()
    assert cf.suggestions
    assert project_hashes(sample_project) == before  # SR-11 write gate


@needs_engine
def test_apply_then_verify_resolves(ws: Workspace, sample_project: Path) -> None:
    sid = ws.case_file(1).suggestions[0].id
    approval = ws.approve(sid, "cli")
    assert approval.outcome == "applied" and approval.backup_path
    assert Path(approval.backup_path, "src/churn/train.py").exists()
    v = ws.verify(1, background=False)
    from faultsage.storage import repo_incidents

    v = repo_incidents.get_verification(ws.conn, v.id) or v
    assert v.result == "resolved"
    assert ws.case_file(1).status == "verified"


@needs_engine
def test_apply_refuses_stale_file(ws: Workspace, sample_project: Path) -> None:
    target = sample_project / "src/churn/train.py"
    target.write_text(target.read_text() + "\n# edited\n")
    git(sample_project, "commit", "-qam", "edit")
    sid = ws.case_file(1).suggestions[0].id
    with pytest.raises(PatchStaleError):
        ws.approve(sid, "cli")
    assert target.read_text().endswith("# edited\n")


@needs_engine
def test_apply_refuses_dirty_git_tree(ws: Workspace, sample_project: Path) -> None:
    (sample_project / "src/churn/clean.py").write_text(
        "# uncommitted\n" + (sample_project / "src/churn/clean.py").read_text()
    )
    sid = ws.case_file(1).suggestions[0].id
    with pytest.raises(GitDirtyError):
        ws.approve(sid, "cli")


