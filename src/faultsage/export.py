"""Case file export to Markdown (FR-36, 03_DATA-RULES section 5). Content is already redacted."""

from __future__ import annotations

from datetime import UTC, datetime

from faultsage import __version__
from faultsage.models.core import CaseFile

LABEL = {"confirmed": "Confirmed", "strong": "Strong", "possible": "Possible", "unknown": "Unknown"}


def to_markdown(cf: CaseFile, project: str) -> str:
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        f"<!-- Generated by FaultSage {__version__} at {now}. Content is redacted. -->",
        f"# I-{cf.incident_id}: {cf.title}",
        "",
        f"Project: {project}  ",
        f"Status: {cf.status}  ",
        f"First seen: {cf.first_seen_at:%Y-%m-%d %H:%M} UTC, last seen {cf.last_seen_at:%Y-%m-%d %H:%M} UTC, "
        f"{cf.occurrence_count} occurrence(s)",
        "",
        "## What failed (Confirmed)",
        "",
    ]
    if cf.exception:
        out.append(
            f"`{cf.exception.type}: {cf.exception.message.splitlines()[0] if cf.exception.message else ''}`"
        )
    if cf.failing_tests:
        out += ["", "Failing tests:", *[f"- `{t}`" for t in cf.failing_tests]]
    if cf.raise_site:
        rs = cf.raise_site
        out.append("")
        out.append(
            f"Raised at `{rs.file_path}:{rs.line}` in `{rs.function}`"
            if rs.available
            else f"Raised in `{rs.file_path}`, line not available"
        )
    out += ["", "## Likely causes", ""]
    for h in cf.hypotheses:
        out.append(f"{h.rank}. **{LABEL[h.certainty]}**: {h.claim}")
        for e in h.evidence:
            out.append(f"   - {e.source}, {e.stance}: {e.summary}")
    if cf.hypotheses and cf.hypotheses[0].weights_version == "untrained":
        out += [
            "",
            "_Ranking weights are untrained (hand-set until the first benchmark training run)._",
        ]
    if cf.impacts:
        out += ["", "## Affected", "", "| Name | Kind | Relation | Basis |", "|---|---|---|---|"]
        out += [f"| `{i.name}` | {i.kind} | {i.relation} | {i.basis} |" for i in cf.impacts]
    for s in cf.suggestions:
        out += ["", f"## Suggested fix S-{s.id} ({s.rule_id}, {s.state})", "", s.explanation]
        if s.patch_diff:
            out += ["", "```diff", s.patch_diff.rstrip(), "```"]
        if s.verify_command:
            out += ["", f"Verify: `{s.verify_command}`"]
    for v in cf.verifications:
        passed = sum(t.outcome == "passed" for t in v.tests)
        out += [
            "",
            f"Verification V-{v.id}: {v.result or 'running'} ({passed} of {len(v.tests)} tests pass)",
        ]
    return "\n".join(out) + "\n"
